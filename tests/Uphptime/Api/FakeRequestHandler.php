namespace Uphptime\Tests\Api;

use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;
use Psr\Http\Server\RequestHandlerInterface;
use Slim\Psr7\Factory\ResponseFactory;

/**
 * A RequestHandlerInterface double recording whether it was reached and the request it received.
 */
final class FakeRequestHandler implements RequestHandlerInterface
{
    public ?ServerRequestInterface $receivedRequest = null;
    public bool $wasCalled                          = false;

    public function handle(ServerRequestInterface $request): ResponseInterface
    {
        $this->wasCalled       = true;
        $this->receivedRequest = $request;

        $response = (new ResponseFactory())->createResponse(200);
        $response->getBody()->write('{"ok":true}');

        return $response;
    }
}
