namespace Uphptime\Scheduling;

use RuntimeException;

/**
 * A non-blocking exclusive run lock, so an overlapping `check:run` exits immediately instead of queuing.
 */
final class Lockfile
{
    /** @var resource|null */
    private $handle = null;

    public function __construct(private readonly string $path) {}

    // Returns false immediately if another run already holds the lock, rather than blocking.
    public function acquire(): bool
    {
        $directory = dirname($this->path);
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new RuntimeException(sprintf('Unable to create directory: %s', $directory));
        }

        $handle = fopen($this->path, 'c');
        if ($handle === false) {
            throw new RuntimeException(sprintf('Unable to open lock file: %s', $this->path));
        }

        if (!flock($handle, LOCK_EX | LOCK_NB)) {
            fclose($handle);

            return false;
        }

        $this->handle = $handle;

        return true;
    }

    public function release(): void
    {
        if ($this->handle !== null) {
            flock($this->handle, LOCK_UN);
            fclose($this->handle);
            $this->handle = null;
        }
    }
}
